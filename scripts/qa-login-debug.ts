import { chromium } from "@playwright/test";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const logs: string[] = [];
page.on("console", (m) => logs.push(`${m.type()}: ${m.text()}`));
page.on("pageerror", (e) => logs.push(`pageerror: ${e.message}`));
page.on("response", (r) => { if (r.status() >= 400) logs.push(`http ${r.status()} ${r.url()}`); });
await page.goto("http://localhost:3010/login", { waitUntil: "networkidle" });
console.log("inputs", await page.locator("input").count());
await page.fill("#email", "maya@settlewise.demo");
await page.fill("#password", "settlewise-demo-2026");
await page.click('button[type="submit"]');
await page.waitForTimeout(5000);
console.log("url", page.url());
console.log("alerts", await page.locator(".alert").allInnerTexts());
console.log("text", (await page.locator("body").innerText()).slice(0, 1600));
console.log("logs", logs);
await page.screenshot({ path: "docs/screenshots/login-after-submit.png", fullPage: true });
await browser.close();
